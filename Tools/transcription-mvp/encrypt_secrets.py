"""Build ``secrets/keys.enc.json`` and ``secrets_shares.py``.

    python encrypt_secrets.py --bigmodel sk-... --mimo sk-... [--qwen sk-...] [--revoke]

The passphrase is 32 bytes of OS randomness, split 3-of-4 with Shamir's Secret
Sharing. Each share is XOR-masked with its own random pad; the masked share and
its pad land in ``secrets_shares.py`` as integer lists, so neither the share nor
the passphrase appears as a contiguous string in the packaged binary. The API
keys themselves only ever exist as AES-256-GCM ciphertext in
``secrets/keys.enc.json``.

Rotating a credential means re-running this command and pushing the new JSON.
``--revoke`` seals a document with ``revoked: true`` and a bumped epoch, which
makes every install that fetches the repository refuse to use the old key.
"""

import argparse
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import secrets_crypto  # noqa: E402

SHARE_COUNT = 4
SHARE_THRESHOLD = 3
PASSPHRASE_BYTES = 32

SHARES_MODULE = HERE / "secrets_shares.py"
DOCUMENT = HERE / "secrets" / "keys.enc.json"


def read_keyring(account):
    try:
        import keyring

        return keyring.get_password("LingoClass", account) or ""
    except Exception:
        return ""


def write_shares_module(shares):
    lines = [
        '"""Generated by encrypt_secrets.py -- do not edit by hand.',
        "",
        "Each entry is (x, masked_share, pad) where masked_share XOR pad is the",
        "Shamir share. Any three of the four reconstruct the passphrase. Stored as",
        "integer lists rather than strings so the values do not survive a `strings`",
        "scan of the packaged binary.",
        '"""',
        "import secrets_crypto",
        "",
        "_ENTRIES = [",
    ]
    for x, share in shares:
        pad = os.urandom(len(share))
        masked = secrets_crypto.mask_share(share, pad)
        lines.append("    (%d, %s, %s)," % (x, list(masked), list(pad)))
    lines += [
        "]",
        "",
        "",
        "def unmasked_shares():",
        "    return [(x, secrets_crypto.mask_share(bytes(masked), bytes(pad)))",
        "            for x, masked, pad in _ENTRIES]",
        "",
    ]
    SHARES_MODULE.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bigmodel", default="")
    parser.add_argument("--mimo", default="")
    parser.add_argument("--qwen", default="")
    parser.add_argument(
        "--revoke", action="store_true", help="seal a document that refuses to open"
    )
    parser.add_argument("--epoch", type=int, default=None, help="defaults to previous epoch + 1")
    arguments = parser.parse_args()

    payload = {}
    for name, value in (
        ("bigmodel", arguments.bigmodel),
        ("mimo", arguments.mimo),
        ("qwen", arguments.qwen),
    ):
        value = (value or "").strip()
        if not value and name != "qwen":
            value = read_keyring("%s-api-key" % name)
        if value:
            payload[name] = value

    previous_epoch = 0
    if DOCUMENT.is_file():
        try:
            previous_epoch = int(json.loads(DOCUMENT.read_text(encoding="utf-8")).get("epoch", 0))
        except (OSError, ValueError):
            previous_epoch = 0
    epoch = arguments.epoch if arguments.epoch is not None else previous_epoch + 1

    passphrase = os.urandom(PASSPHRASE_BYTES)
    shares = secrets_crypto.split_secret(passphrase, SHARE_THRESHOLD, SHARE_COUNT, os.urandom)
    write_shares_module([(share[0], share[1:]) for share in shares])

    body = (
        json.dumps(payload, ensure_ascii=False).encode("utf-8") if not arguments.revoke else b"{}"
    )
    document = secrets_crypto.seal_document(body, passphrase, epoch=epoch, revoked=arguments.revoke)

    DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
    DOCUMENT.write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")

    print("wrote %s (%d bytes)" % (DOCUMENT, DOCUMENT.stat().st_size))
    print("wrote %s" % SHARES_MODULE)
    print(
        "epoch %d, revoked %s, providers %s"
        % (epoch, arguments.revoke, sorted(payload) or "(none)")
    )
    print()
    print("Remember: this credential must be a scoped sub-account key with a quota")
    print("ceiling. Anything shipped to a client can eventually be extracted from a")
    print("fully compromised machine; the ciphertext, scrypt cost and revocation only")
    print("decide how long that takes and how much damage it can do.")


if __name__ == "__main__":
    main()
